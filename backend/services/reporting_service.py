# 1. COMPLIANCE REPORT
# ===========================================================================
def generate_compliance_report_csv(
    db: Session,
    user: UserPrincipal,
    institution_id: Optional[str] = None,
    programme: Optional[str] = None,
    academic_year: Optional[str] = None,
    round_val: Optional[str] = None,
    status_val: Optional[str] = None,
    from_date: Optional[str] = None,
    to_date: Optional[str] = None,
) -> str:
    """
    Generates Statutory Seat Allocation & Quota Compliance Report CSV.
    Contains: approved seats, confirmed, active, provisional counts, utilisation per category,
    exception cases, pending clarifications, and compliance status.
    Missing data is exported as 'N/A', never 0.
    """
    scoped_inst_id = validate_report_access(user, institution_id)
    from_dt, to_dt, reporting_period = parse_date_range(from_date, to_date)

    filters = {
        "institution": scoped_inst_id or "ALL",
        "programme": programme or "",
        "academic_year": academic_year or "",
        "round": round_val or "",
        "status": status_val or "",
        "from_date": from_date or "",
        "to_date": to_date or "",
    }

    # Query matching ProgramApprovals
    aq = db.query(ProgramApproval).join(Institution, ProgramApproval.institution_id == Institution.id)
    if scoped_inst_id:
        aq = aq.filter(ProgramApproval.institution_id == scoped_inst_id)
    if programme:
        aq = aq.filter(ProgramApproval.programme == programme)
    if academic_year:
        aq = aq.filter(ProgramApproval.academic_year == academic_year)

    approvals = aq.all()

    # Pre-fetch institutions for name lookup
    institutions_map = {inst.id: inst for inst in db.query(Institution).all()}

    headers = [
        "Institution ID",
        "Institution Code",
        "Institution Name",
        "Programme",
        "Branch",
        "Academic Year",
        "Approval Ref",
        "Approval Status",
        "Seat Category / Quota",
        "Approved Seats",
        "Confirmed Admissions",
        "Active Admissions",
        "Provisional Admissions",
        "Total Occupied Seats",
        "Category Utilisation (%)",
        "Exception Cases Count",
        "Pending Clarifications Count",
        "Compliance Status",
    ]

    rows = []

    for app in approvals:
        inst = institutions_map.get(app.institution_id)
        inst_code = inst.code if inst else "N/A"
        inst_name = inst.name if inst else "N/A"

        # Allocations by seat type
        allocations = db.query(SeatAllocation).filter(SeatAllocation.approval_id == app.id).all()
        alloc_map = {a.seat_type.value if hasattr(a.seat_type, "value") else str(a.seat_type): a for a in allocations}

        # Query all distinct seat_types present in enrollments to catch unapproved offerings
        enr_seat_types = [
            r[0] for r in (
                db.query(Enrollment.seat_type)
                .filter(Enrollment.approval_id == app.id)
                .distinct()
                .all()
            ) if r[0]
        ]

        all_categories = sorted(list(set(list(alloc_map.keys()) + enr_seat_types)))

        # Also get review cases for this program
        program_cases = (
            db.query(ReviewCase)
            .join(Enrollment, ReviewCase.enrollment_id == Enrollment.id)
            .filter(Enrollment.approval_id == app.id)
            .filter(ReviewCase.status != "RESOLVED")
            .all()
        )

        # Pending correction requests for this approval
        pending_corrections_count = (
            db.query(CorrectionRequest)
            .join(Enrollment, CorrectionRequest.enrollment_id == Enrollment.id)
            .filter(Enrollment.approval_id == app.id)
            .filter(CorrectionRequest.status == "PENDING")
            .count()
        )

        for cat in all_categories:
            alloc = alloc_map.get(cat)
            approved_seats = alloc.approved_count if alloc is not None else None

            # Query enrollments for this approval and seat_type
            eq = db.query(Enrollment).filter(
                Enrollment.approval_id == app.id,
                Enrollment.seat_type == cat,
            )
            if round_val:
                eq = eq.filter(Enrollment.round == round_val)
            if status_val:
                eq = eq.filter(Enrollment.status == status_val)
            if from_dt:
                eq = eq.filter(Enrollment.admission_date >= from_dt)
            if to_dt:
                eq = eq.filter(Enrollment.admission_date <= to_dt)

            cat_enrollments = eq.all()

            confirmed_count = sum(1 for e in cat_enrollments if e.status == "CONFIRMED")
            active_count = sum(1 for e in cat_enrollments if e.status == "ACTIVE")
            provisional_count = sum(1 for e in cat_enrollments if e.status == "PROVISIONAL")
            total_occupied = confirmed_count + active_count

            # Calculate utilisation %
            if approved_seats is not None and approved_seats > 0:
                utilisation_pct = round((confirmed_count / approved_seats) * 100.0, 2)
            else:
                utilisation_pct = None  # Formats as 'N/A'

            # Exception cases count for this seat type
            cat_cases = [c for c in program_cases if getattr(c.enrollment, "seat_type", None) == cat]
            exception_cases_count = len(cat_cases)

            # Clarifications count
            clarifications_count = sum(1 for c in cat_cases if c.status == "AWAITING_INSTITUTION")
            total_clarifications = clarifications_count + pending_corrections_count

            # Determine compliance status
            if approved_seats is None or (alloc is None):
                comp_status = "UNAPPROVED_OFFERING" if confirmed_count > 0 else "NO_APPROVAL"
            elif approved_seats == 0 and confirmed_count > 0:
                comp_status = "UNAPPROVED_OFFERING"
            elif confirmed_count > approved_seats:
                comp_status = "CAPACITY_EXCEEDED"
            elif confirmed_count == approved_seats:
                comp_status = "AT_CAPACITY"
            elif utilisation_pct is not None and utilisation_pct >= 95.0:
                comp_status = "NEAR_LIMIT"
            else:
                comp_status = "COMPLIANT"

            rows.append([
                app.institution_id,
                inst_code,
                inst_name,
                app.programme,
                app.branch,
                app.academic_year,
                app.approval_ref,
                app.status.value if hasattr(app.status, "value") else str(app.status),
                cat,
                approved_seats,  # None -> 'N/A'
                confirmed_count,
                active_count,
                provisional_count,
                total_occupied,
                f"{utilisation_pct}%" if utilisation_pct is not None else None,
                exception_cases_count,
                total_clarifications,
                comp_status,
            ])

    rule_ver = DEFAULT_RULE_VERSION
    if approvals:
        first_alloc = db.query(SeatAllocation).filter(SeatAllocation.approval_id == approvals[0].id).first()
        if first_alloc and first_alloc.rule_version:
            rule_ver = first_alloc.rule_version

    return build_csv_with_metadata(
        report_name="Statutory Seat Allocation & Quota Compliance Report",
        filters=filters,
        reporting_period=reporting_period,
        generated_by=user.user_id,
        role=user.role,
        rule_version=rule_ver,
        denominator_definitions=(
            "Utilisation (%) = (Confirmed Admissions / Approved Seats) * 100. "
            "Category exceptions include unapproved offerings (seats admitted where approved count is N/A or 0) "
            "or category quota exceeds. Pending clarifications include open correction requests and cases awaiting institution."
        ),
        headers=headers,
        rows=rows,
    )


