# 5. TIMELINESS REPORT
# ===========================================================================
def generate_timeliness_report_csv(
    db: Session,
    user: UserPrincipal,
    institution_id: Optional[str] = None,
    programme: Optional[str] = None,
    academic_year: Optional[str] = None,
    round_val: Optional[str] = None,
    status_val: Optional[str] = None,
    from_date: Optional[str] = None,
    to_date: Optional[str] = None,
) -> str:
    """
    Generates Submission Timeliness & Calendar Deadlines Report CSV.
    Missing data is exported as 'N/A', never 0.
    """
    scoped_inst_id = validate_report_access(user, institution_id)
    from_dt, to_dt, reporting_period = parse_date_range(from_date, to_date)

    filters = {
        "institution": scoped_inst_id or "ALL",
        "programme": programme or "",
        "academic_year": academic_year or "",
        "round": round_val or "",
        "status": status_val or "",
        "from_date": from_date or "",
        "to_date": to_date or "",
    }

    q = db.query(Submission).join(Institution, Submission.institution_id == Institution.id)

    if scoped_inst_id:
        q = q.filter(Submission.institution_id == scoped_inst_id)
    if programme:
        q = q.filter(Submission.programme == programme)
    if academic_year:
        q = q.filter(Submission.academic_year == academic_year)
    if round_val:
        q = q.filter(Submission.round == round_val)
    if status_val:
        q = q.filter(Submission.status == status_val)
    if from_dt:
        q = q.filter(Submission.created_at >= from_dt)
    if to_dt:
        q = q.filter(Submission.created_at <= to_dt)

    submissions = q.order_by(Submission.created_at.desc()).all()

    headers = [
        "Submission ID",
        "Institution ID",
        "Institution Code",
        "Institution Name",
        "Programme",
        "Academic Year",
        "Admission Round",
        "Submission Date",
        "Submission Status",
        "Total Submitted Rows",
        "Valid Rows",
        "Invalid Rows",
        "Committed Rows",
        "Failed Rows",
        "Is Locked",
        "Lock Reason",
        "Timeliness Assessment",
    ]

    rows = []
    for sub in submissions:
        inst = sub.institution
        counts = sub.counts or {}

        # Late assessment
        # In Rule 4, final round submissions or locked rounds flag late delivery
        timeliness_assessment = "LATE" if sub.is_locked else "ON_TIME"

        rows.append([
            sub.id,
            sub.institution_id,
            inst.code if inst else None,
            inst.name if inst else None,
            sub.programme,      # None -> 'N/A'
            sub.academic_year, # None -> 'N/A'
            sub.round,
            sub.created_at.isoformat() if sub.created_at else None,
            sub.status,
            counts.get("total", 0),
            counts.get("valid", 0),
            counts.get("invalid", 0),
            counts.get("committed", 0),
            counts.get("failed", 0),
            sub.is_locked,
            sub.lock_reason,   # None -> 'N/A'
            timeliness_assessment,
        ])

    return build_csv_with_metadata(
        report_name="Submission Timeliness & Calendar Deadlines Report",
        filters=filters,
        reporting_period=reporting_period,
        generated_by=user.user_id,
        role=user.role,
        rule_version=DEFAULT_RULE_VERSION,
        denominator_definitions=(
            "Timeliness assessed against statutory calendar deadlines per round. "
            "Submissions after round closing date or locked cutoff are flagged as late."
        ),
        headers=headers,
        rows=rows,
    )


