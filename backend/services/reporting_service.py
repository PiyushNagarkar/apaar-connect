def generate_enrolment_report_csv(
    db: Session,
    user: UserPrincipal,
    institution_id: Optional[str] = None,
    programme: Optional[str] = None,
    academic_year: Optional[str] = None,
    round_val: Optional[str] = None,
    status_val: Optional[str] = None,
    from_date: Optional[str] = None,
    to_date: Optional[str] = None,
) -> str:
    """
    Generates Statutory Student Enrolment Ledger Report CSV.
    Missing data is exported as 'N/A', never 0.
    """
    scoped_inst_id = validate_report_access(user, institution_id)
    from_dt, to_dt, reporting_period = parse_date_range(from_date, to_date)

    filters = {
        "institution": scoped_inst_id or "ALL",
        "programme": programme or "",
        "academic_year": academic_year or "",
        "round": round_val or "",
        "status": status_val or "",
        "from_date": from_date or "",
        "to_date": to_date or "",
    }

    q = (
        db.query(Enrollment)
        .join(Student, Enrollment.student_id == Student.id)
        .join(Institution, Enrollment.institution_id == Institution.id)
        .join(ProgramApproval, Enrollment.approval_id == ProgramApproval.id)
    )

    if scoped_inst_id:
        q = q.filter(Enrollment.institution_id == scoped_inst_id)
    if programme:
        q = q.filter(ProgramApproval.programme == programme)
    if academic_year:
        q = q.filter(Enrollment.academic_year == academic_year)
    if round_val:
        q = q.filter(Enrollment.round == round_val)
    if status_val:
        q = q.filter(Enrollment.status == status_val)
    if from_dt:
        q = q.filter(Enrollment.admission_date >= from_dt)
    if to_dt:
        q = q.filter(Enrollment.admission_date <= to_dt)

    enrollments = q.order_by(Enrollment.admission_date.asc(), Enrollment.created_at.asc()).all()

    headers = [
        "Enrollment ID",
        "Student Name",
        "APAAR ID (Masked)",
        "Gender",
        "Date of Birth",
        "Institution ID",
        "Institution Code",
        "Institution Name",
        "Programme",
        "Branch",
        "Academic Year",
        "Round",
        "Seat Type",
        "Category",
        "Admission Date",
        "Status",
        "Identity Status (L1)",
        "Authority Status (L2)",
        "Compliance Status (L3)",
        "Verified Flag",
        "Record Version",
    ]

    rows = []
    for enr in enrollments:
        student = enr.student
        inst = enr.institution
        app = enr.approval

        rows.append([
            enr.id,
            student.name if student else None,
            student.apaar_masked if student else None,
            student.gender if student else None,
            student.dob.isoformat() if (student and student.dob) else None,
            enr.institution_id,
            inst.code if inst else None,
            inst.name if inst else None,
            app.programme if app else None,
            app.branch if app else None,
            enr.academic_year,
            enr.round,
            enr.seat_type,
            enr.category,
            enr.admission_date.isoformat() if enr.admission_date else None,
            enr.status,
            enr.identity_status,
            enr.authority_status,
            enr.compliance_status,
            enr.verified,
            enr.version,
        ])

    return build_csv_with_metadata(
        report_name="Statutory Student Enrolment Ledger Report",
        filters=filters,
        reporting_period=reporting_period,
        generated_by=user.user_id,
        role=user.role,
        rule_version=DEFAULT_RULE_VERSION,
        denominator_definitions=(
            "Total student admission records submitted in statutory ledger under specified filters. "
            "Verified Flag is TRUE only when all 3 layers (L1 Identity, L2 Authority, L3 Compliance) have PASSED."
        ),
        headers=headers,
        rows=rows,
    )


