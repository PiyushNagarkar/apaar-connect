def generate_data_quality_report_csv(
    db: Session,
    user: UserPrincipal,
    institution_id: Optional[str] = None,
    programme: Optional[str] = None,
    academic_year: Optional[str] = None,
    round_val: Optional[str] = None,
    status_val: Optional[str] = None,
    from_date: Optional[str] = None,
    to_date: Optional[str] = None,
) -> str:
    """
    Generates Data-Quality Score & Ingestion Hygiene Report CSV.
    Evaluates Q = max(0, 100 - (35M + 25V + 20D + 10A + 10T)).
    Includes defect rates, penalties, and explicit component denominators.
    Missing data is exported as 'N/A', never 0.
    """
    scoped_inst_id = validate_report_access(user, institution_id)
    _, _, reporting_period = parse_date_range(from_date, to_date)

    filters = {
        "institution": scoped_inst_id or "ALL",
        "programme": programme or "",
        "academic_year": academic_year or "",
        "from_date": from_date or "",
        "to_date": to_date or "",
    }

    # Institutions to evaluate
    iq = db.query(Institution)
    if scoped_inst_id:
        iq = iq.filter(Institution.id == scoped_inst_id)
    target_institutions = iq.all()

    headers = [
        "Institution ID",
        "Institution Code",
        "Institution Name",
        "Programme",
        "Academic Year",
        "Total Records Evaluated",
        "Data Quality Score (0-100)",
        "Quality Grade Tier",
        "Missing Fields Rate (%)",
        "Missing Fields Penalty Points",
        "Missing Fields Denominator",
        "Validation Errors Rate (%)",
        "Validation Errors Penalty Points",
        "Validation Errors Denominator",
        "Duplicate Cases Rate (%)",
        "Duplicate Cases Penalty Points",
        "Duplicate Cases Denominator",
        "Approval Mismatches Rate (%)",
        "Approval Mismatches Penalty Points",
        "Approval Mismatches Denominator",
        "Late Submissions Rate (%)",
        "Late Submissions Penalty Points",
        "Late Submissions Denominator",
    ]

    rows = []

    for inst in target_institutions:
        dq = compute_data_quality_score(
            db=db,
            institution_id=inst.id,
            programme=programme,
            academic_year=academic_year,
        )

        comps = dq.get("components", {})
        m_comp = comps.get("missing_required_fields", {})
        v_comp = comps.get("unresolved_validation_errors", {})
        d_comp = comps.get("unresolved_duplicate_cases", {})
        a_comp = comps.get("approval_mismatches", {})
        t_comp = comps.get("late_submissions", {})

        total_records = dq.get("total_records_evaluated", 0)

        rows.append([
            inst.id,
            inst.code,
            inst.name,
            programme if programme else "ALL_PROGRAMMES",
            academic_year if academic_year else "ALL_YEARS",
            total_records,
            dq.get("score"),
            dq.get("grade"),
            round(m_comp.get("rate", 0.0) * 100.0, 2),
            m_comp.get("penalty"),
            m_comp.get("denominator"),
            round(v_comp.get("rate", 0.0) * 100.0, 2),
            v_comp.get("penalty"),
            v_comp.get("denominator"),
            round(d_comp.get("rate", 0.0) * 100.0, 2),
            d_comp.get("penalty"),
            d_comp.get("denominator"),
            round(a_comp.get("rate", 0.0) * 100.0, 2),
            a_comp.get("penalty"),
            a_comp.get("denominator"),
            round(t_comp.get("rate", 0.0) * 100.0, 2),
            t_comp.get("penalty"),
            t_comp.get("denominator"),
        ])

    return build_csv_with_metadata(
        report_name="Data Quality Score & Ingestion Hygiene Report",
        filters=filters,
        reporting_period=reporting_period,
        generated_by=user.user_id,
        role=user.role,
        rule_version=DEFAULT_RULE_VERSION,
        denominator_definitions=(
            "Formula: Q = max(0, 100 - (35M + 25V + 20D + 10A + 10T)). "
            "Denominator M: total required fields evaluated (7 fields * total student records). "
            "Denominators V, D, A, T: total student records evaluated in statutory ledger."
        ),
        headers=headers,
        rows=rows,
    )


