def format_cell(value: Any) -> str:
    """Formats a single cell value for regulatory CSV. Missing data is ALWAYS 'N/A', never 0."""
    if value is None:
        return "N/A"
    if isinstance(value, str):
        val = value.strip()
        return val if val else "N/A"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


def build_csv_with_metadata(
    report_name: str,
    filters: Dict[str, Any],
    reporting_period: str,
    generated_by: str,
    role: str,
    rule_version: str,
    denominator_definitions: str,
    headers: List[str],
    rows: List[List[Any]],
) -> str:
    """
    Builds a compliant statutory CSV with leading metadata rows (prefixed with '#')
    followed by the CSV data table.
    """
    # 1. Format metadata filter string
    active_filters = []
    for k, v in sorted(filters.items()):
        if v is not None and v != "":
            active_filters.append(f"{k}={v}")
    filters_str = "; ".join(active_filters) if active_filters else "NONE (All accessible records)"

    now_iso = datetime.now(timezone.utc).isoformat()

    metadata_lines = [
        f"# Report Name: {report_name}",
        f"# Applied Filters: {filters_str}",
        f"# Reporting Period: {reporting_period}",
        f"# Generated At: {now_iso}",
        f"# Generated By: {generated_by} ({role})",
        f"# Rule Version: {rule_version}",
        f"# Denominator Definitions: {denominator_definitions}",
        "#",
    ]
    metadata_block = "\n".join(metadata_lines) + "\n"

    # 2. Write CSV data table using standard csv writer
    output = io.StringIO()
    writer = csv.writer(output, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    writer.writerow(headers)
    for row in rows:
        formatted_row = [format_cell(val) for val in row]
        writer.writerow(formatted_row)

    return metadata_block + output.getvalue()


def validate_report_access(
    user: UserPrincipal,
    target_institution_id: Optional[str],
) -> Optional[str]:
    """
    Enforces server-side role and institutional scoping:
    - Checks that user role is permitted.
    - If user is an institution user, strictly enforces target_institution_id == user.institution_id.
    - If institution user attempts to access another institution, raises 403 Forbidden.
    - Returns scoped institution_id (or None if central user without filter).
    """
    if user.role not in ALLOWED_REPORT_ROLES:
        raise ForbiddenError(f"Role '{user.role}' is not authorized to generate or export statutory reports.")

    is_inst_user = user.role in [ROLE_INSTITUTION_ADMIN, ROLE_INSTITUTION_OPERATOR]
    if is_inst_user:
        if not user.institution_id:
            raise ForbiddenError("Institution user is not associated with any valid institution ID.")
        if target_institution_id and target_institution_id != user.institution_id:
            raise ForbiddenError(
                f"Scope violation: User belongs to institution '{user.institution_id}', "
                f"and cannot access reports for institution '{target_institution_id}'."
            )
        return user.institution_id

    # Central administrative or audit roles
    return target_institution_id or None


def parse_date_range(from_date_str: Optional[str], to_date_str: Optional[str]) -> Tuple[Optional[datetime], Optional[datetime], str]:
    """Parses optional ISO from_date and to_date and generates reporting period label."""
    from_dt: Optional[datetime] = None
    to_dt: Optional[datetime] = None

    if from_date_str:
        try:
            from_dt = datetime.fromisoformat(from_date_str.replace("Z", "+00:00"))
        except Exception:
            try:
                from_dt = datetime.strptime(from_date_str, "%Y-%m-%d").replace(tzinfo=timezone.utc)
            except Exception:
                from_dt = None

    if to_date_str:
        try:
            to_dt = datetime.fromisoformat(to_date_str.replace("Z", "+00:00"))
        except Exception:
            try:
                to_dt = datetime.strptime(to_date_str, "%Y-%m-%d").replace(tzinfo=timezone.utc)
            except Exception:
                to_dt = None

    if from_dt and to_dt:
        period_label = f"{from_dt.date().isoformat()} to {to_dt.date().isoformat()}"
    elif from_dt:
        period_label = f"From {from_dt.date().isoformat()} onwards"
    elif to_dt:
        period_label = f"Up to {to_dt.date().isoformat()}"
    else:
        period_label = "ALL (Entire academic ledger)"

    return from_dt, to_dt, period_label


